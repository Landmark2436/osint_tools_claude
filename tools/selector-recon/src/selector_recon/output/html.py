def render_html(result: RunResult) -> str:
    data = json.dumps(result_to_dict(result), ensure_ascii=False)
    # Inside <script> only "<" can end the element early; escape it as a JSON unicode escape.
    data = data.replace("<", "\\u003c")
    return _TEMPLATE.replace("__VERSION__", escape(result.tool_version)).replace("__DATA__", data)


def write_html(result: RunResult, path: Path) -> Path:
    path.write_text(render_html(result), encoding="utf-8")
    return path
